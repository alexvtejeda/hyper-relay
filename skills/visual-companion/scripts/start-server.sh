#!/usr/bin/env bash
# Start the brainstorm server and output connection info
# Usage: start-server.sh [--project-dir <path>] [--host <bind-host>] [--url-host <display-host>] [--foreground] [--background]
#
# Starts server on a random high port, outputs JSON with URL.
# Each session gets its own directory to avoid conflicts.
#
# Options:
#   --project-dir <path>  Store session files under <path>/.superpowers/brainstorm/
#                         instead of /tmp. Files persist after server stops.
#   --host <bind-host>    Host/interface to bind (default: 127.0.0.1).
#                         Use 0.0.0.0 in remote/containerized environments.
#   --url-host <host>     Hostname shown in returned URL JSON.
#   --foreground          Run server in the current terminal (no backgrounding).
#   --background          Force background mode (overrides Codex auto-foreground).

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# Parse arguments
PROJECT_DIR=""
SESSION_NAME=""
SESSION_GIVEN="false"
FOREGROUND="false"
FORCE_BACKGROUND="false"
BIND_HOST="127.0.0.1"
URL_HOST=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --project-dir)
      PROJECT_DIR="$2"
      shift 2
      ;;
    --session)
      SESSION_NAME="$2"
      SESSION_GIVEN="true"
      shift 2
      ;;
    --host)
      BIND_HOST="$2"
      shift 2
      ;;
    --url-host)
      URL_HOST="$2"
      shift 2
      ;;
    --foreground|--no-daemon)
      FOREGROUND="true"
      shift
      ;;
    --background|--daemon)
      FORCE_BACKGROUND="true"
      shift
      ;;
    *)
      echo "{\"error\": \"Unknown argument: $1\"}"
      exit 1
      ;;
  esac
done

if [[ -z "$URL_HOST" ]]; then
  if [[ "$BIND_HOST" == "127.0.0.1" || "$BIND_HOST" == "localhost" ]]; then
    URL_HOST="localhost"
  else
    URL_HOST="$BIND_HOST"
  fi
fi

# Some environments reap detached/background processes. Auto-foreground when detected.
if [[ -n "${CODEX_CI:-}" && "$FOREGROUND" != "true" && "$FORCE_BACKGROUND" != "true" ]]; then
  FOREGROUND="true"
fi

# Windows/Git Bash reaps nohup background processes. Auto-foreground when detected.
if [[ "$FOREGROUND" != "true" && "$FORCE_BACKGROUND" != "true" ]]; then
  case "${OSTYPE:-}" in
    msys*|cygwin*|mingw*) FOREGROUND="true" ;;
  esac
  if [[ -n "${MSYSTEM:-}" ]]; then
    FOREGROUND="true"
  fi
fi

# Session identity. A NAME makes a restart idempotent — same directory, same screens,
# same URL — which is what makes the idle timeout harmless. Without one we keep the old
# ephemeral id so non-interactive callers still work; the SKILL requires a name.
if [[ "$SESSION_GIVEN" == "true" ]]; then
  if [[ ! "$SESSION_NAME" =~ ^[a-z0-9][a-z0-9-]{0,63}$ ]]; then
    echo "{\"error\": \"Invalid --session name '$SESSION_NAME': must match ^[a-z0-9][a-z0-9-]{0,63}\$ — one path segment, lowercase, no slashes or dots\"}"
    exit 1
  fi
  SESSION_ID="$SESSION_NAME"
else
  SESSION_ID="$$-$(date +%s)"
fi

if [[ -n "$PROJECT_DIR" ]]; then
  SESSION_DIR="${PROJECT_DIR}/.superpowers/brainstorm/${SESSION_ID}"
else
  SESSION_DIR="/tmp/brainstorm-${SESSION_ID}"
fi

STATE_DIR="${SESSION_DIR}/state"
PID_FILE="${STATE_DIR}/server.pid"
LOG_FILE="${STATE_DIR}/server.log"

# Reuse the session directory when it already exists. content/ is NEVER cleared — the
# screens written before a restart are the whole reason for naming sessions.
mkdir -p "${SESSION_DIR}/content" "$STATE_DIR"

# A stale pid file means the previous server died without cleaning up. Clear the markers
# it should have cleared itself, so the liveness check below cannot read a lie.
if [[ -f "$PID_FILE" ]]; then
  old_pid=$(cat "$PID_FILE")
  if ! kill -0 "$old_pid" 2>/dev/null; then
    rm -f "$PID_FILE" "${STATE_DIR}/server-info"
  fi
fi

# If a server is already serving THIS session, hand back its info rather than starting a
# second one on the same directory. Two servers on one content dir both "work" and each
# reports a different URL, which is exactly the confusion naming is meant to end.
if [[ -f "$PID_FILE" && -f "${STATE_DIR}/server-info" ]]; then
  running_pid=$(cat "$PID_FILE")
  if kill -0 "$running_pid" 2>/dev/null; then
    cat "${STATE_DIR}/server-info"
    exit 0
  fi
fi

# Reuse the port this session bound last time so the URL is stable and can be stated once.
# server.cjs falls back to a random high port if it is taken, and rewrites state/port with
# whatever it actually bound.
REQUESTED_PORT=""
if [[ -f "${STATE_DIR}/port" ]]; then
  REQUESTED_PORT="$(tr -d '[:space:]' < "${STATE_DIR}/port")"
fi

cd "$SCRIPT_DIR"

# Resolve the harness PID (grandparent of this script).
# $PPID is the ephemeral shell the harness spawned to run us — it dies
# when this script exits. The harness itself is $PPID's parent.
OWNER_PID="$(ps -o ppid= -p "$PPID" 2>/dev/null | tr -d ' ')"
if [[ -z "$OWNER_PID" || "$OWNER_PID" == "1" ]]; then
  OWNER_PID="$PPID"
fi

# Foreground mode for environments that reap detached/background processes.
if [[ "$FOREGROUND" == "true" ]]; then
  echo "$$" > "$PID_FILE"
  env BRAINSTORM_DIR="$SESSION_DIR" BRAINSTORM_PORT="$REQUESTED_PORT" BRAINSTORM_HOST="$BIND_HOST" BRAINSTORM_URL_HOST="$URL_HOST" BRAINSTORM_OWNER_PID="$OWNER_PID" node server.cjs
  exit $?
fi

# Start server, capturing output to log file
# Use nohup to survive shell exit; disown to remove from job table
nohup env BRAINSTORM_DIR="$SESSION_DIR" BRAINSTORM_PORT="$REQUESTED_PORT" BRAINSTORM_HOST="$BIND_HOST" BRAINSTORM_URL_HOST="$URL_HOST" BRAINSTORM_OWNER_PID="$OWNER_PID" node server.cjs > "$LOG_FILE" 2>&1 &
SERVER_PID=$!
disown "$SERVER_PID" 2>/dev/null
echo "$SERVER_PID" > "$PID_FILE"

# Wait for server-started message (check log file)
for i in {1..50}; do
  if grep -q "server-started" "$LOG_FILE" 2>/dev/null; then
    # Verify server is still alive after a short window (catches process reapers)
    alive="true"
    for _ in {1..20}; do
      if ! kill -0 "$SERVER_PID" 2>/dev/null; then
        alive="false"
        break
      fi
      sleep 0.1
    done
    if [[ "$alive" != "true" ]]; then
      echo "{\"error\": \"Server started but was killed. Retry in a persistent terminal with: $SCRIPT_DIR/start-server.sh${PROJECT_DIR:+ --project-dir $PROJECT_DIR} --host $BIND_HOST --url-host $URL_HOST --foreground\"}"
      exit 1
    fi
    grep "server-started" "$LOG_FILE" | head -1
    exit 0
  fi
  sleep 0.1
done

# Timeout - server didn't start
echo '{"error": "Server failed to start within 5 seconds"}'
exit 1
